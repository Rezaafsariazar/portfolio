// Post-build: write dist/_headers with a Content-Security-Policy whose script hashes
// match the inline scripts Astro emitted in this build. Run after `astro build`.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;

const htmlFiles = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? htmlFiles(full) : name.endsWith('.html') ? [full] : [];
  });

const sha256 = (s) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`;

const scriptHashes = new Set();
const styleHashes = new Set();
for (const file of htmlFiles(DIST)) {
  const html = readFileSync(file, 'utf8');
  for (const [, body] of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) {
    if (body.trim()) scriptHashes.add(sha256(body));
  }
  for (const [, body] of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)) {
    if (body.trim()) styleHashes.add(sha256(body));
  }
  if (/\sstyle="/.test(html)) {
    throw new Error(`Inline style attribute in ${file}: move it to a class, it would be blocked by the CSP.`);
  }
}

const csp = [
  "default-src 'none'",
  `script-src 'self' ${[...scriptHashes].join(' ')}`.trim(),
  `style-src 'self' ${[...styleHashes].join(' ')}`.trim(),
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "manifest-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

const headers = `# Generated by scripts/headers.mjs — edit that file, not this one.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), microphone=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`;

writeFileSync(join(DIST, '_headers'), headers);
console.log(`[headers] wrote dist/_headers (${scriptHashes.size} script hash(es), ${styleHashes.size} style hash(es))`);
